"""Shared pieces of the evaluation framework: uncertainty helpers and the standard machine-readable report header.

Every report states its EVIDENCE CLASS so that synthetic results can never be mistaken for real-world ones:
  synthetic_fixture         inputs generated by the project (rendered pages, synthesised speech, written questions); says the code works, not that it works on real data
  simulated_degradation     real inputs with faults added by code
  public_research_dataset   real data from a published research dataset (licence and provenance recorded)
  real_world_clinical       real clinical data from the intended setting; NONE exists in this repository
Thresholds are never changed here to make a result pass; gates live in one place (training/trainer.py GATES) and are reported, not edited."""
from __future__ import annotations

import hashlib
import json
import platform
import sys
import time
from pathlib import Path
from typing import Callable

import numpy as np

SCHEMA = "cosmo-eval-1"
EVIDENCE_CLASSES = ("synthetic_fixture", "simulated_degradation", "public_research_dataset", "real_world_clinical")


def wilson(k: int, n: int, z: float = 1.96) -> list[float] | None:
    """Wilson score interval for a proportion k/n (95 %). None when n == 0."""
    if n <= 0:
        return None
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * np.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return [round(float(max(0.0, c - h)), 4), round(float(min(1.0, c + h)), 4)]


def bootstrap(fn: Callable[[np.ndarray], float], n: int, n_boot: int = 1000, seed: int = 0, ndigits: int = 4) -> list[float] | None:
    """Percentile bootstrap 95 % CI of fn(index_array) over resampled indices."""
    if n < 5:
        return None
    rng = np.random.default_rng(seed)
    vals = []
    for _ in range(n_boot):
        idx = rng.integers(0, n, n)
        try:
            vals.append(fn(idx))
        except (ValueError, ZeroDivisionError):
            continue
    if len(vals) < max(20, n_boot // 5):
        return None
    lo, hi = np.percentile(vals, [2.5, 97.5])
    return [round(float(lo), ndigits), round(float(hi), ndigits)]


def sha256_json(obj) -> str:
    return hashlib.sha256(json.dumps(obj, sort_keys=True, ensure_ascii=False, separators=(",", ":"), default=str).encode()).hexdigest()


def header(name: str, evidence_class: str, config: dict, dataset: dict | None = None, notes: list[str] | None = None) -> dict:
    """Standard header: what was evaluated, on what evidence, with which code, configuration and environment."""
    if evidence_class not in EVIDENCE_CLASSES:
        raise ValueError(f"unknown evidence class {evidence_class!r}")
    from ..provenance import code_revision
    h = {"schema": SCHEMA, "name": name, "created_at": time.strftime("%Y-%m-%dT%H:%M:%S%z"), "evidence_class": evidence_class,
         "real_world_evidence": evidence_class == "real_world_clinical", "code_revision": code_revision(), "config": config, "config_sha256": sha256_json(config),
         "dataset": dataset or {}, "environment": {"python": sys.version.split()[0], "platform": platform.system(), "numpy": np.__version__}, "notes": notes or []}
    try:
        import torch
        h["environment"]["torch"] = torch.__version__
    except ImportError:
        pass
    return h


def write_report(path: Path, report: dict) -> Path:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(report, indent=2, ensure_ascii=False, default=str), encoding="utf-8")
    return path
