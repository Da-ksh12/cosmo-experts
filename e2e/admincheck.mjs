import { chromium } from "playwright";
const dir = process.argv[2];
const b = await chromium.launch(); const ctx = await b.newContext({ viewport: { width: 1280, height: 900 } }); const p = await ctx.newPage();
const errs = []; p.on("pageerror", (e) => errs.push(String(e))); p.on("console", (m) => m.type() === "error" && !m.text().includes("Failed to load resource") && errs.push(m.text()));
await p.goto("http://localhost:3000/login");
await p.selectOption("select", "admin1"); await p.fill("input[type=password]", "cosmo-dev"); await p.click("button[type=submit]");
await p.waitForURL((u) => !u.pathname.startsWith("/login"));
await p.goto("http://localhost:3000/admin"); await p.waitForSelector("text=Train a model");
await p.waitForSelector("text=Release gates (evaluation)", { timeout: 20000 });
await p.waitForSelector("text=Job queue", { timeout: 20000 }); await p.waitForSelector("text=not enabled", { timeout: 20000 });
const txt = await p.textContent("main");
const ok = (c, m) => console.log((c ? "PASS " : "FAIL ") + m);
ok(txt.includes("Baseline: majority class"), "model card shows baselines");
ok(txt.includes("critical class sensitivity"), "gate: critical-class sensitivity shown");
ok(txt.includes("ood detection"), "gate: OOD detection shown");
ok(txt.includes("Not clinically validated"), "'Not clinically validated' label shown");
ok(txt.includes("PAD-UFES-20") || txt.includes("pad-ufes-20"), "dataset registry shows PAD-UFES-20");
ok(txt.includes("CC BY 4.0") || txt.includes("CC-BY-4.0"), "verified licence shown");
ok(!txt.includes("approved_for_defined_use") || !txt.match(/Approved for defined use/), "no model shown as approved");
ok(txt.includes("Job queue") && txt.includes("llm"), "system readiness + queue shown");
await p.screenshot({ path: dir + "/shots/admin-ai-studio.png", fullPage: true });
ok(errs.length === 0, "no console errors " + JSON.stringify(errs.slice(0, 2)));
await b.close();
