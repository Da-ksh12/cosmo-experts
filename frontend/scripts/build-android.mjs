// Builds the Android app from the real UI:  static export  ->  Capacitor sync  ->  (optional) debug APK.
//
//   node scripts/build-android.mjs            export + sync only
//   node scripts/build-android.mjs --apk      ... and build android/app/build/outputs/apk/debug/*.apk with Gradle
//   node scripts/build-android.mjs --no-local ignore android.config.local.json (for the bundle check in e2e/android-bundle.mjs)
//
// Settings: android.config.json (defaults) overridden by android.config.local.json (yours, ignored by Git). Nothing secret belongs there: it holds only a server address,
// the hosts a DEBUG build may reach over plain http, and the app name. Needs JAVA_HOME (JDK 21) and ANDROID_HOME for --apk.
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const androidDir = path.resolve(root, "..", "android");
const win = process.platform === "win32";
const read = (f) => (fs.existsSync(path.join(root, f)) ? JSON.parse(fs.readFileSync(path.join(root, f), "utf8")) : {});
const noLocal = process.argv.includes("--no-local");          // ignore android.config.local.json (used by the bundle check, which must start with no server chosen)
const cfg = { devCleartextHosts: ["10.0.2.2", "localhost"], apiBase: "", ...read("android.config.json"), ...(noLocal ? {} : read("android.config.local.json")) };
const wantApk = process.argv.includes("--apk");

function run(cmd, args, opts = {}) {
  const r = win ? spawnSync([/\s/.test(cmd) ? `"${cmd}"` : cmd, ...args].join(" "), { cwd: opts.cwd ?? root, stdio: "inherit", shell: true, env: { ...process.env, ...(opts.env ?? {}) } })       // Windows needs a shell for .cmd files; the arguments are constants of this script
                : spawnSync(cmd, args, { cwd: opts.cwd ?? root, stdio: "inherit", env: { ...process.env, ...(opts.env ?? {}) } });
  if (r.status !== 0) { console.error(`\nFAILED: ${cmd} ${args.join(" ")} (exit ${r.status})`); process.exit(r.status || 1); }
}

// 1. the address, if one is baked in, must be https (or http on a private network, which Android then still checks)
if (cfg.apiBase) {
  const u = new URL(cfg.apiBase);
  const priv = /^(localhost|127\.\d+\.\d+\.\d+|10\.\d+\.\d+\.\d+|192\.168\.\d+\.\d+|172\.(1[6-9]|2\d|3[01])\.\d+\.\d+|[^.]+\.local)$/i.test(u.hostname);
  if (u.protocol !== "https:" && !(u.protocol === "http:" && priv)) { console.error(`apiBase ${cfg.apiBase} must be https:// (http:// only for a private-network host).`); process.exit(2); }
  if (u.username || u.password) { console.error("apiBase must not contain credentials."); process.exit(2); }
}

// 2. static export of the real UI
console.log(`\n== 1/4 static export (server: ${cfg.apiBase || "chosen in the app"})`);
fs.rmSync(path.join(root, "out-android"), { recursive: true, force: true });
run("npx", ["next", "build"], { env: { NEXT_PUBLIC_TARGET: "android", NEXT_PUBLIC_API_BASE: cfg.apiBase, NEXT_PUBLIC_APP_VERSION: cfg.versionName ?? "0.1.0-demo", NEXT_TELEMETRY_DISABLED: "1" } });
if (!fs.existsSync(path.join(root, "out-android", "index.html"))) { console.error("The export did not produce out-android/index.html"); process.exit(3); }

// 3. the native project (created once, then kept in Git)
console.log("\n== 2/4 Android project");
if (!fs.existsSync(path.join(androidDir, "app", "build.gradle"))) run("npx", ["cap", "add", "android"]);

// 4. the debug build may use plain http for development hosts only; the release build never may (main/res/xml keeps the strict default)
const xml = `<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by frontend/scripts/build-android.mjs from android.config*.json. DEBUG builds only. -->
<network-security-config>
    <base-config cleartextTrafficPermitted="false">
        <trust-anchors><certificates src="system" /></trust-anchors>
    </base-config>
    <domain-config cleartextTrafficPermitted="true">
${cfg.devCleartextHosts.map((h) => `        <domain includeSubdomains="false">${h}</domain>`).join("\n")}
    </domain-config>
</network-security-config>
`;
const dbgXml = path.join(androidDir, "app", "src", "debug", "res", "xml");
fs.mkdirSync(dbgXml, { recursive: true });
fs.writeFileSync(path.join(dbgXml, "network_security_config.xml"), xml);

console.log("\n== 3/4 Capacitor sync");
run("npx", ["cap", "sync", "android"]);

if (wantApk) {
  console.log("\n== 4/4 Gradle assembleDebug");
  run(path.join(androidDir, win ? "gradlew.bat" : "gradlew"), ["assembleDebug", "--console=plain"], { cwd: androidDir });
  const dir = path.join(androidDir, "app", "build", "outputs", "apk", "debug");
  const apks = fs.existsSync(dir) ? fs.readdirSync(dir).filter((f) => f.endsWith(".apk")) : [];
  if (!apks.length) { console.error(`No APK found in ${dir}`); process.exit(4); }
  for (const a of apks) console.log(`\nAPK: ${path.join(dir, a)}  (${(fs.statSync(path.join(dir, a)).size / 1048576).toFixed(1)} MB)`);
} else {
  console.log("\n== 4/4 skipped (no --apk). Build the APK with:  node scripts/build-android.mjs --apk");
}
